import {Mycelium} from "./mycelium.js";
import {OpenEnd} from "./openEnd.js";

class GameState {
    #mycelia;
    #screen;
    #delay;
    #dragOver;
    #backgroundCanvas;
    #backgroundCtx;
    #pause;

    constructor(mycelia, delay, backgroundCanvas) {
        if (this.#myceliaValidation(mycelia)) {
            this.#mycelia = mycelia;
        }
        this.#screen = this.#createScreen();
        if (this.#delayValidation(delay)) {
            this.#delay = delay;
        }
        this.#dragOver = undefined;
        if (this.#backgroundCanvasValidation(backgroundCanvas)) {
            this.#backgroundCanvas = backgroundCanvas;
            this.#backgroundCtx = backgroundCanvas.getContext('2d');
        }
        this.#pause = false;
    }
    
    get mycelia() {
        return this.#mycelia;
    }

    set mycelia(value) {
        if (this.#myceliaValidation(value)) {
            this.#mycelia = value;
        }
    }
    
    get screen() {
        return this.#screen;
    }

    //there is no screen setter. Screen 2d array is generated by the gameState
    //constructor (see createScreen method). This method ensures that the array is
    //accessed via a proxy with appropriate validation for additions to the
    //screen array

    get delay() {
        return this.#delay;
    }

    set delay(value) {
        if (this.#delayValidation(value)) {
            this.#delay = value;
        }
    }

    get dragOver() {
        return this.#dragOver;
    }

    set dragOver(value) {
        if (this.#dragOverValidation(value)) {
            this.#dragOver = value;
        }
    }

    get backgroundCanvas() {
        return this.#backgroundCanvas;
    }

    set backgroundCanvas(value) {
        if (this.#backgroundCanvasValidation(value)) {
            this.#backgroundCanvas = value;
            this.#backgroundCtx = value.getContext('2d');
        }
    }

    get backgroundCtx() {
        return this.#backgroundCtx;
    }

    get pause() {
        return this.#pause;
    }

    set pause(value) {
        if (this.#pauseValidation(value)) {
            this.#pause = value;
        }
    }

    #myceliaValidation(value) {
        if (!Array.isArray(value)) {
            throw new Error('Invalid mycelia on GameState');
        } else {
            value.forEach(val => {
                if (val.constructor.name !== Mycelium.name) {
                    throw new Error('Invalid mycelia on GameState');
                }
            });
        }
        return true;
    }

    // screen array contains object at each x,y position. Currently has just one key
    // 'mycelium' which contains name of mycelium
    #createScreen() {
        const result = [];
        for (let i = 0; i < 1200; i++) {
            result[i] = [];
            result[i] = new Proxy(result[i], {
                set(obj, prop, value) {
                    if ((typeof value) == "object") {
                        for (const [k, v] of Object.entries(value)) {
                            if (k != 'mycelium') {
                                throw new Error('Invalid screen on GameState');
                            }
                            if ((typeof v) != "string") {
                                throw new Error('Invalid screen on GameState');
                            }
                        }
                        obj[prop] = value;
                        return true;
                    } else {
                        throw new Error('Invalid screen on GameState');
                    }
                }
            });
        };
        return result;
    }

    #delayValidation(value) {
        if (!Number.isInteger(value)) {
            throw new Error('Invalid delay on GameState');
        }
        if (value < 1) {
            throw new Error('Invalid delay on GameState');
        }
        return true;
    }

    #dragOverValidation(value) {
        if (value !== undefined && (typeof value) != 'string') {
            throw new Error('Invalid dragOver on GameState');
        }
        return true;
    }

    #backgroundCanvasValidation(value) {
        if (value.tagName != 'CANVAS') {
            throw new Error('Invalid backgroundCanvas on GameState');
        }
        return true;
    }

    #pauseValidation(value) {
        if (value != false && value != true) {
            throw new Error('Invalid pause on GameState');
        }
        return true;
    }

    findMyceliumByName(name) {
        for (let i=0; i<this.mycelia.length; i++) {
            if (this.mycelia[i].name == name) {
                return this.mycelia[i];
            }
        }
    }

    setupStartingMycelia() {
        //remove between 0 and 3 random mycelia from the starting 5
        let noOfMyceliaToRemove = Math.floor(Math.random * 4);
        for (let i=0; i<noOfMyceliaToRemove; i++) {
            let indexToRemove = Math.floor(Math.random * this.mycelia.length);
            this.mycelia.splice(indexToRemove, 1);
        }
        //generate random xposn and yposn for each mycelium. Each must be at
        //least 100 from the edge and from each other.


        //generate random starting openEnds for each mycelium.


        //draws starting mycelia plus populates screen array
        for (let i=0; i<this.mycelia.length; i++) {
            this.mycelia[i].canvas.width = 2400;
            this.mycelia[i].canvas.height = 1400;
            this.mycelia[i].ctx.globalCompositeOperation = "source-over";
            this.mycelia[i].ctx.fillStyle = this.mycelia[i].colour;
            let x = this.mycelia[i].startPosn.xposn;
            let y = this.mycelia[i].startPosn.yposn;
            this.mycelia[i].ctx.fillRect(x*2, y*2, 4, 4);
            this.screen[x][y] = {mycelium: this.mycelia[i].name};
            this.mycelia[i].openEnds.forEach(openEnd => {
                openEnd.drawMyc(this.mycelia[i]);
                this.screen[openEnd.xposn][openEnd.yposn] = {mycelium: this.mycelia[i].name};
            });
        }
    }

    run() {
        if (!this.pause) {
            this.mycelia.forEach(mycelium => {
                if (!mycelium.bigEnough()) {
                    mycelium.growAllOpenEnds(this.screen);
                }
            }); 
        }
        setTimeout(() => {this.run();}, this.delay);
    }

}


export { GameState };
